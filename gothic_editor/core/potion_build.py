"""Apply potion components and script-item actions to staging sources only."""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from .daedalus_merge import (
    DaedalusMergeError, ScriptTree, declaration_text, definitions, target_path,
)
from .potion_components import PotionComponents
from .scripts import load_text,parse_items
from .action_build import prepare_actions
from .item_layout import project_scripts
from .categories import classify
from .scroll_cast import configure_scroll_cast


def apply_potions(project: Path, content: Path):
    store = PotionComponents(project)
    replacements, additions, helpers = store.generated()
    script_items=[]
    for path in (project_scripts(project)/'Content').rglob('*'):
        if path.is_file() and path.suffix.lower()=='.d':
            script_items.extend(item for item in parse_items(path,'project')
                                if classify(item)=='scrolls' and item.editor_metadata.get('item_actions'))
    if not replacements and not additions and not helpers and not script_items:
        return []
    tree = ScriptTree(content)
    handlers,action_sources,action_files,tree=prepare_actions(store,content,tree,helpers,script_items)
    if handlers:
        replacements,additions,helpers=store.generated(handlers)
        helpers.extend(action_sources)
    changes = defaultdict(list)
    helpers.extend(configure_scroll_cast(script_items,handlers,tree,changes))
    requests = {}
    missing = []

    def request(name, kind, source, label):
        key = name.casefold()
        if key in requests:
            raise DaedalusMergeError(f'Неоднозначная замена {name}: {requests[key]} / {label}')
        parsed = definitions(source, label)
        if (len(parsed) != 1 or parsed[0].kind != kind
                or tuple(ident.casefold() for ident in parsed[0].names) != (key,)):
            raise DaedalusMergeError(f'{label}: неверное определение {name}')
        location = tree.unique(name, kind)
        if location is None:
            return False
        requests[key] = label
        path, original = location
        if tuple(ident.casefold() for ident in original.names) != (key,):
            raise DaedalusMergeError(f'{label}: нельзя частично заменить группу {original.names} ({path})')
        changes[path].append((original.start, original.end, declaration_text(source, parsed[0])))
        return True

    for name, source in replacements.items():
        if not request(name, 'instance', source, str(store.root / name)):
            missing.append(name)
    if missing:
        raise DaedalusMergeError('Не найдены оригинальные INSTANCE: ' + ', '.join(sorted(missing)))

    # Metadata overrides are opt-in; informational references never emit symbols.
    for file in store.files():
        for metadata, array, kind in (
            ('functions.json', 'source_functions', 'func'),
            ('params.json', 'source_constants', 'const'),
        ):
            path = file.parent / metadata
            if not path.exists():
                continue
            for definition in json.loads(path.read_text('utf-8')).get(array, []):
                if not definition.get('override'):
                    continue
                name = store._safe_id(definition['code'])
                source = definition['source'] if kind == 'func' else (
                    f"const {definition['type']} {name} = {definition['expression']};")
                if not request(name, kind, source, str(path)):
                    raise DaedalusMergeError(f'{path}: не найдено определение {name}')

    for block in additions:
        parsed = definitions(block, 'new potion')
        if len(parsed) != 1 or parsed[0].kind != 'instance':
            raise DaedalusMergeError('Неверное определение нового зелья')
    generated = '\n\n'.join(helpers + [block.rstrip().rstrip(';') + ';' for block in additions])
    names = set()
    for definition in definitions(generated, 'generated potion definitions'):
        for name in definition.names:
            key = name.casefold()
            if key in names or tree.symbols.get(key):
                raise DaedalusMergeError('Конфликт идентификатора нового определения: ' + name)
            names.add(key)

    # Validate every requested/generated symbol before writing the staging tree.
    for path,edits in changes.items():
        previous_end=-1
        for start,end,_ in sorted(edits):
            if start<previous_end:
                raise DaedalusMergeError(f'Конфликт изменений в {path}: проверьте ручные переопределения заклинаний.')
            previous_end=end
    tree.apply(changes)
    affected = {path.relative_to(content) for path in changes}|action_files
    if generated:
        output = target_path(content, Path('Items/GE_ComponentPotions.d'))
        if output.is_file():
            text, codec = load_text(output)
        else:
            text, codec = '// Generated by Gothic Editor - do not edit\n', 'cp1251'
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes((text + '\n' + generated + '\n').encode(codec))
        affected.add(output.relative_to(content))
    return sorted(affected, key=lambda path: path.as_posix().casefold())
