"""Regression tests for uniform Assets menus, Delete undo, and script line endings."""
import tempfile
import tkinter as tk
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

from gothic_editor.core.asset_files import AssetFiles
from gothic_editor.core.edit_history import EditHistory
from gothic_editor.core.scripts import parse_items, write_modified_item
from gothic_editor.ui.panels.resources import ResourcesPanel


class ResourceFileTests(unittest.TestCase):
    def test_can_create_script_and_markdown_in_any_assets_folder(self):
        with tempfile.TemporaryDirectory() as temp:
            project=Path(temp)
            folder=project/'Assets/Custom'
            folder.mkdir(parents=True)
            files=AssetFiles(project)
            script=files.create(folder,'NewAction',script=True)
            markdown=files.create(folder,'Description',markdown=True)
            self.assertEqual(script.name,'NewAction.d')
            self.assertEqual(markdown.name,'Description.md')
            self.assertNotIn(b'\r\r\n',script.read_bytes())
            self.assertNotIn(b'\r\r\n',markdown.read_bytes())

    def test_repeated_script_edits_preserve_crlf_and_russian_text(self):
        with tempfile.TemporaryDirectory() as temp:
            path=Path(temp)/'Item.d'
            original=('// Generated by Gothic Editor\r\n'
                      'INSTANCE ItWr_Test (C_Item)\r\n'
                      '{\r\n'
                      '    name = "Старый свиток";\r\n'
                      '    description = "Описание";\r\n'
                      '};\r\n')
            path.write_bytes(original.encode('cp1251'))
            for value in ('"Первое изменение"','"Второе изменение"'):
                item=parse_items(path,'project')[0]
                write_modified_item(item,path,{'name':value},
                                    metadata={'document_text':'Assets/Texts/Test.md'})
                data=path.read_bytes()
                self.assertNotIn(b'\r\r\n',data)
                self.assertNotIn(b'\n\n\n',data)
                self.assertEqual(data.count(b'\r\n'),7)
            self.assertIn('Второе изменение',path.read_bytes().decode('cp1251'))
            self.assertEqual(len(parse_items(path,'project')),1)

    def test_delete_directory_and_undo_restores_file_bytes(self):
        with tempfile.TemporaryDirectory() as temp:
            root=Path(temp)
            folder=root/'Assets/Custom'
            folder.mkdir(parents=True)
            file=folder/'Action.d'
            file.write_bytes(b'\xff\x00\r\n')
            history=EditHistory()
            history.reset(root)
            before=history.capture((folder,))
            AssetFiles(root).delete(folder)
            self.assertTrue(history.record(before))
            self.assertTrue(history.apply())
            self.assertEqual(file.read_bytes(),b'\xff\x00\r\n')


class ResourceMenuTests(unittest.TestCase):
    def setUp(self):
        try:self.root=tk.Tk()
        except tk.TclError as error:self.skipTest(str(error))
        self.addCleanup(self.root.destroy)
        self.panel=ResourcesPanel(self.root,lambda:'',lambda:None)
        self.panel.pack()
        self.panel.project=Path(tempfile.mkdtemp())
        self.addCleanup(lambda:__import__('shutil').rmtree(self.panel.project))
        self.panel.assets.mkdir()
        self.panel.folder=self.panel.assets
        self.root.update_idletasks()

    def test_all_three_create_actions_exist_in_each_folder(self):
        folder=self.panel.assets/'Other'
        folder.mkdir()
        calls=[]
        self.panel.create_resource=lambda script=False,**kw:calls.append((script,kw))
        for target in (self.panel.assets,folder):
            menu=tk.Menu(self.root,tearoff=False)
            self.panel._add_create_commands(menu,target)
            labels=[menu.entrycget(i,'label') for i in range(menu.index('end')+1)]
            self.assertEqual(len(labels),3)
            self.assertIn('Создать скрипт (.d)',labels)
            self.assertIn('Создать Markdown-документ (.md)',labels)
            for i in range(3):menu.invoke(i)
            self.assertEqual([item[1]['folder'] for item in calls[-3:]], [target]*3)
            menu.destroy()

    def test_delete_hotkey_uses_confirmation_and_history(self):
        target=self.panel.assets/'Folder'
        target.mkdir()
        (target/'file.txt').write_text('data')
        history=EditHistory()
        history.reset(self.panel.project)
        self.panel.history=lambda:history
        self.panel._selected=target
        with patch('gothic_editor.ui.panels.resources.messagebox.askyesno',return_value=True):
            self.panel._delete_shortcut(SimpleNamespace(widget=self.panel.scroll_area.canvas))
        self.assertFalse(target.exists())
        self.assertTrue(history.apply())
        self.assertEqual((target/'file.txt').read_text(),'data')
